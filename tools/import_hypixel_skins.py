#!/usr/bin/env python3
# Part of HypixelMinions - https://github.com/Irisss01/Minions-remake
"""
Downloads the real Hypixel SkyBlock minion head textures (all tiers) from the public NotEnoughUpdates item repo
and writes a skins.yml for the HypixelMinions plugin.

  python3 tools/import_hypixel_skins.py                 -> ./skins.yml
  python3 tools/import_hypixel_skins.py --out path/to/plugins/HypixelMinions/skins.yml

Then run /minions reload in game. Needs internet. Tiers that cannot be downloaded are skipped
(the minion then just uses the default / dyed-helmet look for that tier).
"""
import argparse, json, re, sys, urllib.request, urllib.error

BASE = "https://raw.githubusercontent.com/NotEnoughUpdates/NotEnoughUpdates-REPO/master/items/{iid}_GENERATOR_{tier}.json"
# plugin minion id -> Hypixel item id prefix
MINIONS = {
    "cobblestone": "COBBLESTONE", "coal": "COAL", "iron": "IRON", "gold": "GOLD", "diamond": "DIAMOND",
    "lapis": "LAPIS", "redstone": "REDSTONE", "emerald": "EMERALD", "quartz": "QUARTZ", "obsidian": "OBSIDIAN",
    "glowstone": "GLOWSTONE", "gravel": "GRAVEL", "sand": "SAND", "wheat": "WHEAT", "carrot": "CARROT",
    "potato": "POTATO", "pumpkin": "PUMPKIN", "melon": "MELON", "oak": "OAK", "birch": "BIRCH",
    "spruce": "SPRUCE", "jungle": "JUNGLE", "acacia": "ACACIA", "dark_oak": "DARK_OAK",
}
VALUE = re.compile(r'Value:\\?"([A-Za-z0-9+/=]{20,})\\?"')


def fetch(iid, tier):
    url = BASE.format(iid=iid, tier=tier)
    try:
        with urllib.request.urlopen(url, timeout=20) as r:
            data = json.loads(r.read().decode("utf-8"))
    except (urllib.error.URLError, urllib.error.HTTPError, ValueError):
        return None
    m = VALUE.search(data.get("nbttag", ""))
    return m.group(1) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="skins.yml")
    out = ap.parse_args().out
    lines = ["# generated by tools/import_hypixel_skins.py", ""]
    total = 0
    for mid, iid in MINIONS.items():
        got = {}
        for tier in range(1, 13):
            v = fetch(iid, tier)
            if v:
                got[tier] = v
        print(f"{mid:12} {len(got):2}/12 tiers", flush=True)
        if not got:
            continue
        lines.append(f"{mid.upper()}:")
        for tier, v in got.items():
            lines.append(f'  "{tier}": "{v}"')
        total += len(got)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nWrote {total} textures to {out}. Put it in plugins/HypixelMinions/ and run /minions reload.")
    if total == 0:
        print("Nothing downloaded - check your internet connection.", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
